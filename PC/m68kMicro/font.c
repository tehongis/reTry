void font_init(u8* mem_ptr, u32 fb_start_addr, int fb_width, int fb_height) {
    g_mem = mem_ptr;
    g_fb_start = fb_start_addr;
    g_fb_width = fb_width;
    g_fb_height = fb_height;
    g_fb_size = fb_width * fb_height;
    g_cursor_x = 0;
    g_cursor_y = 0;
    g_blink_state = 0;
}

void framebuffer_clear(void) {
    memset(&g_mem[g_fb_start], 0, g_fb_size);
    g_cursor_x = 0;
    g_cursor_y = 0;
}

void framebuffer_scroll_up(void) {
    u8* fb = &g_mem[g_fb_start];
    int shift_bytes = g_fb_width * 8;
    memmove(fb, fb + shift_bytes, g_fb_size - shift_bytes);
    memset(fb + g_fb_size - shift_bytes, 0, shift_bytes);
    if (g_cursor_y > 0) g_cursor_y--;
}

// UUSI FUNKTIO: Päivitellään kursorin vilkkumista kerran ruudussa (n. 300ms välein)
void font_update_cursor(void) {
    static int counter = 0;
    counter++;
    if (counter >= 20) { // Vilkutetaan n. kolmasosasekunnin välein
        g_blink_state = !g_blink_state;
        counter = 0;
    }

    u8* fb = &g_mem[g_fb_start];
    int start_row = g_cursor_y * 8;
    int start_col = g_cursor_x * 8;

    // Piirretään tai pyyhitään kursori (laatikko) sen mukaan, mikä blink_state on
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            int offset = (start_row + row) * g_fb_width + (start_col + col);
            if (offset < g_fb_size) {
                // Indeksi 1 = Valkoinen laatikko kursoriksi
                if (g_blink_state && row >= 6) { // Alaviivatyyppinen kursori
                    fb[offset] = 1;
                } else if (!g_blink_state && row >= 6) {
                    fb[offset] = 0;
                }
            }
        }
    }
}

void framebuffer_print_char(char c) {
    // Ennen merkin piirtoa pyyhitään kursori alta pois
    u8* fb = &g_mem[g_fb_start];
    int start_row = g_cursor_y * 8;
    int start_col = g_cursor_x * 8;
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            fb[(start_row + row) * g_fb_width + (start_col + col)] = 0;
        }
    }

    if (c == '\n' || c == '\r') {
        g_cursor_x = 0;
        g_cursor_y++;
        if (g_cursor_y >= 32) {
            framebuffer_scroll_up();
            g_cursor_y = 31;
        }
        return;
    }

    c = (char)toupper((unsigned char)c);
    if (c < 32 || c > 90) return;
    int font_idx = c - 32;

    for (int row = 0; row < 8; row++) {
        u8 font_byte = g_font_rom[font_idx][row];
        for (int col = 0; col < 8; col++) {
            if (font_byte & (0x80 >> col)) {
                fb[(start_row + row) * g_fb_width + (start_col + col)] = 1;
            }
        }
    }

    g_cursor_x++;
    if (g_cursor_x >= 40) {
        g_cursor_x = 0;
        g_cursor_y++;
        if (g_cursor_y >= 32) {
            framebuffer_scroll_up();
            g_cursor_y = 31;
        }
    }
}
